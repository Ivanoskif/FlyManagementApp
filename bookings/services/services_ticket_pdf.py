from __future__ import annotations
from io import BytesIO
from decimal import Decimal
from django.utils import timezone
from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas
from reportlab.lib.units import mm
from bookings.models import Booking


def build_ticket_pdf_bytes(*, booking: Booking) -> bytes:
    buf = BytesIO()
    c = canvas.Canvas(buf, pagesize=A4)
    w, h = A4

    left = 18 * mm
    y = h - 20 * mm
    line = 6 * mm

    def txt(s: str, size=10, bold=False):
        nonlocal y
        c.setFont("Helvetica-Bold" if bold else "Helvetica", size)
        c.drawString(left, y, s)
        y -= line

    # Header
    txt("FLIGHT TICKET / CONFIRMATION", size=14, bold=True)
    y -= 2 * mm

    # Booking
    ticket_no = getattr(getattr(booking, "ticket", None), "ticket_number", None) or "—"
    txt(f"Booking code: {booking.booking_code}", bold=True)
    txt(f"Ticket number: {ticket_no}", bold=True)
    txt(f"Status: {booking.status}")

    y -= 2 * mm
    c.line(left, y, w - left, y)
    y -= 8 * mm

    # Flight info
    f = booking.flight
    dep = timezone.localtime(f.scheduled_departure).strftime("%Y-%m-%d %H:%M")
    arr = timezone.localtime(f.scheduled_arrival).strftime("%Y-%m-%d %H:%M")
    txt("Flight details", bold=True)
    txt(f"Flight: {f.flight_number} · Airline: {f.airline.name}")
    txt(f"Route: {f.origin.iata_code} → {f.destination.iata_code}")
    txt(f"Departure: {dep}")
    txt(f"Arrival: {arr}")
    txt(f"Fare class: {booking.fare_class.name}")

    y -= 2 * mm
    c.line(left, y, w - left, y)
    y -= 8 * mm

    # Passengers
    txt("Passengers", bold=True)
    pax = list(booking.passengers.all().order_by("id"))
    if not pax:
        txt("— No passengers saved", size=10)
    else:
        for i, p in enumerate(pax, start=1):
            seat = p.seat_no or "—"
            txt(f"{i}. {p.first_name} {p.last_name} · DOB: {p.date_of_birth} · Seat: {seat}")

    y -= 2 * mm
    c.line(left, y, w - left, y)
    y -= 8 * mm

    # Payment summary
    total = booking.total_amount or Decimal("0.00")
    txt("Payment summary", bold=True)
    txt(f"Total paid: {total} {booking.currency}")

    y -= 6 * mm
    txt("Generated by Fly Management", size=9)
    txt(timezone.localtime(timezone.now()).strftime("Generated at: %Y-%m-%d %H:%M"), size=9)

    c.showPage()
    c.save()

    pdf = buf.getvalue()
    buf.close()
    return pdf
