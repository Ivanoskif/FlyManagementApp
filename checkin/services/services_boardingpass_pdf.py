from __future__ import annotations
from io import BytesIO
from django.utils import timezone
from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas
from bookings.models import Booking


def build_boarding_pass_pdf_bytes(*, booking_id: int) -> bytes:
    booking = (
        Booking.objects
        .select_related("flight", "flight__origin", "flight__destination", "flight__airline", "user")
        .prefetch_related("passengers")
        .get(id=booking_id)
    )

    passengers = [p for p in booking.passengers.all().order_by("id") if p.checked_in]

    buffer = BytesIO()
    c = canvas.Canvas(buffer, pagesize=A4)
    width, height = A4

    y = height - 60
    c.setFont("Helvetica-Bold", 16)
    c.drawString(50, y, "BOARDING PASS")
    y -= 20

    c.setFont("Helvetica", 10)
    c.drawString(50, y, f"Booking: {booking.booking_code}   Status: {booking.status}")
    y -= 14
    c.drawString(50, y, f"Flight: {booking.flight.flight_number} ({booking.flight.airline.name})")
    y -= 14
    c.drawString(50, y, f"Route: {booking.flight.origin.iata_code} -> {booking.flight.destination.iata_code}")
    y -= 14
    c.drawString(50, y, f"Departure: {timezone.localtime(booking.flight.scheduled_departure)}")
    y -= 14
    c.drawString(50, y, f"Arrival:   {timezone.localtime(booking.flight.scheduled_arrival)}")
    y -= 20

    c.setFont("Helvetica-Bold", 12)
    c.drawString(50, y, "Checked-in passengers")
    y -= 16

    if not passengers:
        c.setFont("Helvetica", 10)
        c.drawString(50, y, "No passengers checked-in yet.")
        y -= 14
    else:
        c.setFont("Helvetica", 10)
        for idx, p in enumerate(passengers, start=1):
            seat = p.seat_no or "—"
            line = f"{idx}. {p.first_name} {p.last_name} | DOB: {p.date_of_birth} | Seat: {seat}"
            c.drawString(50, y, line)
            y -= 14
            if y < 80:
                c.showPage()
                y = height - 60
                c.setFont("Helvetica", 10)

    c.setFont("Helvetica-Oblique", 9)
    c.drawString(50, 40, f"Generated by Fly Management at {timezone.localtime(timezone.now())}")
    c.showPage()
    c.save()

    return buffer.getvalue()
